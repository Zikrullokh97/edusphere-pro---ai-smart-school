export function useI18n(lang: AppLanguage) {
  return (key: string): string => {
    return TRANSLATIONS[lang]?.[key] || TRANSLATIONS['uz']?.[key] || TRANSLATIONS['ru']?.[key] || TRANSLATIONS['en']?.[key] || key;
  };
}

export function formatRole(role: UserRole, lang: AppLanguage): string {
  const t = useI18n(lang);
  switch (role) {
    case 'admin':
      return t('adminRoleName');
    case 'teacher':
      return t('teacherRoleName');
    case 'parent_student':
      return t('parentStudentRoleName');
    default:
      return role;
  }
}

export function formatGrade(gradeNum: number, lang: AppLanguage): string {
  const t = useI18n(lang);
  switch (gradeNum) {
    case 5:
      return t('grade5Label');
    case 4:
      return t('grade4Label');
    case 3:
      return t('grade3Label');
    case 2:
      return t('grade2Label');
    default:
      return `${gradeNum}`;
  }
}

export function formatQuarter(quarterId: string, lang: AppLanguage): string {
  const t = useI18n(lang);
  switch (quarterId) {
    case 'Q1':
      return t('q1Label');
    case 'Q2':
      return t('q2Label');
    case 'Q3':
      return t('q3Label');
    case 'Q4':
      return t('q4Label');
    default:
      return quarterId;
  }
}

export function formatMonth(monthIndex: number, lang: AppLanguage): string {
  const list = MONTH_NAMES[lang] || MONTH_NAMES['uz'];
  return list[monthIndex % 12] || '';
}

export function formatWeekday(dayIndex: number, lang: AppLanguage): string {
  const list = WEEKDAY_NAMES[lang] || WEEKDAY_NAMES['uz'];
  return list[dayIndex % 7] || '';
}

export function formatDateLocalized(dateInput: string | Date, lang: AppLanguage): string {
  const d = typeof dateInput === 'string' ? new Date(dateInput) : dateInput;
  if (isNaN(d.getTime())) return typeof dateInput === 'string' ? dateInput : '';
  const day = d.getDate();
  const month = formatMonth(d.getMonth(), lang);
  const year = d.getFullYear();
  return `${day}-${month}, ${year}`;
}
