import test from 'node:test';
import assert from 'node:assert/strict';
import { buildLessonSession, getLessonSessions, getScheduleDay } from '../src/lib/lessonSessions.ts';
import type { ScheduleSlot } from '../src/types.ts';

const slot: ScheduleSlot = {
  id: 'slot-7a-math-1',
  day: 'THU',
  period: 1,
  time: '08:00 - 08:45',
  subject: 'Mathematics',
  className: '7-A',
  teacherName: 'Teacher A',
  room: '304',
  classId: 'class-7a',
  subjectId: 'math-01',
};

test('lesson session ID is deterministic and date-scoped', () => {
  const a = buildLessonSession(slot, '2026-08-20');
  const b = buildLessonSession(slot, '2026-08-20');
  const c = buildLessonSession(slot, '2026-08-27');
  assert.equal(a.sessionId, b.sessionId);
  assert.notEqual(a.sessionId, c.sessionId);
  assert.equal(a.sessionId, 'session-slot-7a-math-1-2026-08-20');
});

test('same student/date/lesson produces one canonical attendance key', () => {
  const session = buildLessonSession(slot, '2026-08-20');
  const key = (schoolId: string, studentId: string, classId: string, date: string, lessonId: string) =>
    `att-${schoolId}-${classId}-${date}-${lessonId}-${studentId}`;
  assert.equal(key('school-a', 'student-1', 'class-7a', session.date, session.sessionId),
    key('school-a', 'student-1', 'class-7a', session.date, session.sessionId));
});

test('same student/date but different lesson sessions are allowed', () => {
  const first = buildLessonSession({ ...slot, id: 'slot-1' }, '2026-08-20');
  const second = buildLessonSession({ ...slot, id: 'slot-2', period: 2 }, '2026-08-20');
  assert.notEqual(first.sessionId, second.sessionId);
});

test('cross-school attendance keys cannot collide', () => {
  const session = buildLessonSession(slot, '2026-08-20');
  const key = (schoolId: string) => `att-${schoolId}-class-7a-${session.date}-${session.sessionId}-student-1`;
  assert.notEqual(key('school-a'), key('school-b'));
});

test('schedule day and session selection are tied to the actual date', () => {
  assert.equal(getScheduleDay('2026-08-20'), 'THU');
  assert.equal(getLessonSessions([slot], '7-A', '2026-08-20').length, 1);
  assert.equal(getLessonSessions([slot], '7-A', '2026-08-21').length, 0);
  assert.throws(() => getScheduleDay('2026-08-23'), /Sunday/);
});

test('legacy lesson IDs are not generated by the session resolver', () => {
  const session = buildLessonSession(slot, '2026-08-20');
  assert.equal(session.sessionId.startsWith('legacy-'), false);
});
